export type MessageKey = keyof typeof messages.es;

export function t(language: Language, key: MessageKey): string {
  return messages[language][key] ?? messages.es[key];
}

export function relationMessageKey(type: string): MessageKey {
  const key = `relation${type.charAt(0).toUpperCase()}${type.slice(1)}` as MessageKey;
  return key in messages.es ? key : "relationModerate";
}

export function sourceMessageKey(type: string): MessageKey {
  const map: Record<string, MessageKey> = {
    documented_fact: "sourceDocumentedFact",
    client_report: "sourceClientReport",
    caregiver_report: "sourceCaregiverReport",
    third_party_report: "sourceThirdPartyReport",
    professional_observation: "sourceProfessionalObservation",
    professional_inference: "sourceProfessionalInference",
    working_hypothesis: "sourceWorkingHypothesis",
    unknown: "sourceUnknown",
  };
  return map[type] ?? "sourceUnknown";
}

export function flowMessageKey(flow: string): MessageKey {
  const map: Record<string, MessageKey> = {
    toward_center: "toCenter",
    away_from_center: "fromCenter",
    mutual: "mutual",
    none: "noDirection",
  };
  return map[flow] ?? "noDirection";
}
